clc;
clear;
close all;
data = csvread('SensorData.csv');
LDR = data(:,1);
POT = data(:,2);
N = length(LDR);
BatteryCapacity = 2500;
ActiveCurrent = 15;
TransmitCurrent = 40;
SleepCurrent = 0.01;
Interval = 10;
ActiveTime = 0.5;
TransmitTime = 0.2;
SleepTime = Interval-ActiveTime-TransmitTime;
TotalTime = N*Interval;
ActiveTotal = N*ActiveTime;
TransmitTotal = N*TransmitTime;
SleepTotal = N*SleepTime;
ActiveCharge = ActiveCurrent*ActiveTotal/3600;
TransmitCharge = TransmitCurrent*TransmitTotal/3600;
SleepCharge = SleepCurrent*SleepTotal/3600;
TotalCharge = ActiveCharge+TransmitCharge+SleepCharge;
AverageCurrent = TotalCharge/(TotalTime/3600);
LifeHours = BatteryCapacity/AverageCurrent;
LifeDays = LifeHours/24;
LifeMonths = LifeDays/30;
BatteryUsed = TotalCharge/BatteryCapacity*100;
fprintf('Number of Sensor Samples       : %d\n',N);
fprintf('Number of Sampling Events      : %d\n',N);
fprintf('Number of Transmission Events : %d\n',N);
fprintf('Sampling Interval              : %.2f seconds\n',Interval);
fprintf('Active Time per Cycle          : %.2f seconds\n',ActiveTime);
fprintf('Transmission Time per Cycle   : %.2f seconds\n',TransmitTime);
fprintf('Sleep Time per Cycle           : %.2f seconds\n',SleepTime);
fprintf('Average Current                : %.3f mA\n',AverageCurrent);
fprintf('Charge Consumed                : %.3f mAh\n',TotalCharge);
fprintf('Battery Used                   : %.3f %%\n',BatteryUsed);
fprintf('Estimated Battery Life         : %.2f hours\n',LifeHours);
fprintf('Estimated Battery Life         : %.2f days\n',LifeDays);
fprintf('Estimated Battery Life         : %.2f months\n',LifeMonths);
figure;
plot(LDR,'LineWidth',1.5);
grid on;
xlabel('Sampling Event');
ylabel('LDR Sensor Value');
title('Sensor Data Used for Battery Life Estimation');
figure;
stem(1:N,ones(N,1),'filled');
grid on;
xlabel('Sampling Event');
ylabel('Transmission Status');
title('IoT Sensor Transmission Events');
ylim([0 1.5]);
Intervals = [5 10 20 30 60];
LifeDays = zeros(size(Intervals));
for i = 1:length(Intervals)
    T = Intervals(i);
    Sleep = T-ActiveTime-TransmitTime;
    Avg = (ActiveCurrent*ActiveTime + ...
           TransmitCurrent*TransmitTime + ...
           SleepCurrent*Sleep)/T;
    LifeDays(i) = BatteryCapacity/Avg/24;
end
figure;
plot(Intervals,LifeDays,'-o','LineWidth',2);
grid on;
xlabel('Sampling Interval (seconds)');
ylabel('Estimated Battery Life (Days)');
title('Effect of Sampling Interval on Battery Life');
figure;
pie([ActiveCharge TransmitCharge SleepCharge]);
title('Charge Consumption by IoT Device State');
legend('Active','Transmission','Sleep');